"""Keep Staxa's self-contained Dockerfile tied to the reviewed runtime stage."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
TAIL = '''FROM runtime AS staxa
# Build context MUST be the repository root, not deploy/staxa.
COPY --chown=odoo:odoo addons/ /mnt/extra-addons/
COPY deploy/staxa/entrypoint.py /opt/field-crm/staxa-entrypoint.py
USER odoo
EXPOSE 8069
ENTRYPOINT ["python3", "/opt/field-crm/staxa-entrypoint.py"]
CMD []
'''


def generated():
    source = (ROOT / '.devcontainer/Dockerfile').read_text()
    marker = '\nFROM runtime AS development\n'
    if source.count(marker) != 1:
        raise ValueError('Review runtime stage boundary before regenerating')
    return '# Generated by deploy/staxa/generate_dockerfile.py; do not edit.\n' + source.split(marker)[0].rstrip() + '\n\n' + TAIL


if __name__ == '__main__':
    path = Path(__file__).with_name('Dockerfile')
    content = generated()
    if sys.argv[1:] == ['--check']:
        if path.read_text() != content:
            raise SystemExit('Staxa Dockerfile has drifted from the shared runtime')
        print('PASS: Staxa Dockerfile matches shared runtime')
    elif not sys.argv[1:]:
        path.write_text(content)
    else:
        raise SystemExit('Usage: generate_dockerfile.py [--check]')
