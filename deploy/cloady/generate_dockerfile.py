"""Generate Cloady's image from the shared, security-patched runtime."""
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[2]
TAIL = '''FROM runtime AS cloady
USER root
RUN apt-get update && apt-get install -y --no-install-recommends postgresql-client-16 \\
    && rm -rf /var/lib/apt/lists/*
COPY --chown=odoo:odoo addons/ /mnt/extra-addons/
COPY deploy/staxa/entrypoint.py /opt/field-crm/staxa-entrypoint.py
COPY deploy/cloady/startup.py /opt/field-crm/startup.py
USER odoo
EXPOSE 8069
ENTRYPOINT ["python3", "/opt/field-crm/startup.py"]
CMD []
'''
def generated():
    source = (ROOT / '.devcontainer/Dockerfile').read_text()
    marker = '\nFROM runtime AS development\n'
    if source.count(marker) != 1:
        raise ValueError('Review shared runtime stage boundary')
    return '# Generated by deploy/cloady/generate_dockerfile.py\n' + source.split(marker)[0].rstrip() + '\n\n' + TAIL
if __name__ == '__main__':
    path = Path(__file__).with_name('Dockerfile')
    if sys.argv[1:] == ['--check']:
        assert path.read_text() == generated(), 'Runtime parity failure'
    elif not sys.argv[1:]:
        path.write_text(generated())
    else:
        raise SystemExit('Usage: generate_dockerfile.py [--check]')
